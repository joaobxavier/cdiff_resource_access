    strainColors, false);
title(axD, sprintf('Glutamate (strain effect q=%.3g)', ...
    glutamateGlobal.BenjaminiHochbergQ), 'FontWeight', 'bold');
panelLabel(axD, 'D');

outputFile = fullfile(figureDir, ...
    'figure3_gcms_metabolic_programs.png');
