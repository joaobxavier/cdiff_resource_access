%% Local functions
function plotPlsdaBiplot(ax, scores, loadings, components, ...
        strainOrder, colors, markers, titleLines, showLegend, ...
        variancePrecision)
hold(ax, 'on');
xline(ax, 0, 'Color', [0.88, 0.88, 0.88]);
yline(ax, 0, 'Color', [0.88, 0.88, 0.88]);
scoreMatrix = [scores.PLS1Score, scores.PLS2Score];
loadingMatrix = [loadings.PLS1Loading, loadings.PLS2Loading];
scoreRadius = 0.68 * min(max(abs(scoreMatrix(:, 1))), ...
    max(abs(scoreMatrix(:, 2))));
loadingScale = scoreRadius / max(vecnorm(loadingMatrix, 2, 2));
scaledLoading = loadingMatrix .* loadingScale;
labelPosition = spreadLoadingLabels(1.08 .* scaledLoading);

% Outline the observed within-strain score spread. With only three matched
% batches per strain, these are descriptive covariance ellipses rather than
% inferential confidence regions.
for g = 1:numel(strainOrder)
    row = scores.Strain == strainOrder(g);
    drawObservedScoreEllipse(ax, scoreMatrix(row, :), colors(g, :));
end

for j = 1:height(loadings)
    quiver(ax, 0, 0, scaledLoading(j, 1), scaledLoading(j, 2), 0, ...
        'Color', [0.53, 0.57, 0.60], 'LineWidth', 0.9, ...
        'MaxHeadSize', 0.18, 'HandleVisibility', 'off');
    text(ax, labelPosition(j, 1), labelPosition(j, 2), ...
        loadings.Metabolite(j), ...
        'FontName', 'Arial', 'FontSize', 7, ...
        'Color', [0.25, 0.28, 0.30], ...
        'HorizontalAlignment', horizontalAlignment(labelPosition(j, 1)), ...
        'VerticalAlignment', 'middle');
end

legendHandle = gobjects(numel(strainOrder), 1);
for g = 1:numel(strainOrder)
    for b = 1:3
        row = scores.Strain == strainOrder(g) & scores.Batch == b;
        scatter(ax, scores.PLS1Score(row), scores.PLS2Score(row), 62, ...
            colors(g, :), markers{b}, 'filled', 'MarkerEdgeColor', 'w', ...
            'LineWidth', 0.8, 'HandleVisibility', 'off');
    end
    row = scores.Strain == strainOrder(g);
    centroid = [mean(scores.PLS1Score(row)), mean(scores.PLS2Score(row))];
    legendHandle(g) = scatter(ax, centroid(1), centroid(2), 145, ...
        colors(g, :), 'o', 'filled', ...
        'MarkerEdgeColor', [0.14, 0.14, 0.14], 'LineWidth', 1.1);
end
axis(ax, 'equal');
box(ax, 'off');
set(ax, 'FontName', 'Arial', 'FontSize', 9, 'LineWidth', 0.9);
xlabel(ax, sprintf('PLS1 score (%.*f%% X variance)', ...
    variancePrecision, 100 * components.XVarianceFraction(1)));
ylabel(ax, sprintf('PLS2 score (%.*f%% X variance)', ...
    variancePrecision, 100 * components.XVarianceFraction(2)));
title(ax, titleLines, 'FontWeight', 'bold');
if showLegend
    legend(ax, legendHandle, strainOrder, 'Location', 'southoutside', ...
        'NumColumns', 3, 'Box', 'off', 'FontSize', 7.5);
end
end


function labelPosition = spreadLoadingLabels(labelPosition)
% Separate nearby loading labels vertically while retaining arrow direction.
for side = [-1, 1]
    if side < 0
        index = find(labelPosition(:, 1) < 0);
    else
        index = find(labelPosition(:, 1) >= 0);
    end
    if numel(index) < 2
        continue
    end
    [originalY, order] = sort(labelPosition(index, 2));
    sortedIndex = index(order);
    verticalSpan = max(range(labelPosition(:, 2)), 0.1);
    minimumSeparation = 0.055 * verticalSpan;
    adjustedY = originalY;
    for k = 2:numel(adjustedY)
        adjustedY(k) = max(adjustedY(k), ...
            adjustedY(k - 1) + minimumSeparation);
    end
    adjustedY = adjustedY + mean(originalY) - mean(adjustedY);
    labelPosition(sortedIndex, 2) = adjustedY;
end
end


function drawObservedScoreEllipse(ax, scoreValues, color)
assert(size(scoreValues, 1) >= 3 && size(scoreValues, 2) == 2, ...
    'A score ellipse requires at least three two-dimensional observations.');
center = mean(scoreValues, 1);
centered = scoreValues - center;
covarianceMatrix = cov(scoreValues);
[eigenvector, eigenvalue] = eig(covarianceMatrix, 'vector');
assert(all(eigenvalue > 0), ...
    'Within-strain score covariance must be positive definite.');

mahalanobisSquared = sum((centered / covarianceMatrix) .* centered, 2);
outlineScale = 1.04 * sqrt(max(mahalanobisSquared));
theta = linspace(0, 2 * pi, 181);
unitCircle = [cos(theta); sin(theta)];
ellipse = center' + eigenvector * ...
    diag(outlineScale .* sqrt(eigenvalue)) * unitCircle;
patch(ax, ellipse(1, :), ellipse(2, :), color, ...
    'FaceAlpha', 0.055, 'EdgeColor', color, 'EdgeAlpha', 0.78, ...
    'LineWidth', 1.15, 'HandleVisibility', 'off');
end

function plotExtracellularMetabolite(ax, long, target, strainOrder, ...
        colors, connectFocused)
hold(ax, 'on');
jitter = [-0.10; 0; 0.10];
% Pale zero-to-mean fills reproduce the author's artwork, behind all data.
for g = 1:numel(strainOrder)
    rows = long.Strain == strainOrder(g) & long.Metabolite == target;
    average = mean(long.MatchedLog2ResidualRatio(rows));
    pale = 0.945 * [1,1,1] + 0.055 * colors(g,:);
    patch(ax, g+[-0.17,0.17,0.17,-0.17], [0,0,average,average], ...
        pale, 'FaceColor', pale, 'EdgeColor', 'none', ...
        'HandleVisibility', 'off');
end
if connectFocused
    for b = 1:3
        row75 = long.Strain == "ST1-75" & long.Batch == b & ...
            long.Metabolite == target;
        row68 = long.Strain == "ST1-68" & long.Batch == b & ...
            long.Metabolite == target;
        plot(ax, [1 + jitter(b), 2 + jitter(b)], ...
            [long.MatchedLog2ResidualRatio(row75), ...
            long.MatchedLog2ResidualRatio(row68)], '-', ...
            'Color', [0.72, 0.74, 0.76], 'LineWidth', 1.0, ...
            'HandleVisibility', 'off');
    end
end
for g = 1:numel(strainOrder)
    rows = find(long.Strain == strainOrder(g) & long.Metabolite == target);
    [~, order] = sort(long.Batch(rows));
    rows = rows(order);
    scatter(ax, g + jitter, long.MatchedLog2ResidualRatio(rows), 58, ...
        colors(g, :), 'filled', 'MarkerEdgeColor', 'w', ...
        'LineWidth', 0.8);
    plot(ax, [g - 0.17, g + 0.17], ...
        repmat(mean(long.MatchedLog2ResidualRatio(rows)), 1, 2), '-', ...
        'Color', colors(g, :), 'LineWidth', 2.2);
end
yline(ax, 0, '--', 'Color', [0.56, 0.56, 0.56]);
set(ax, 'XTick', 1:numel(strainOrder), 'XTickLabel', strainOrder, ...
    'XTickLabelRotation', 25, 'FontName', 'Arial', 'FontSize', 9, ...
    'Box', 'off', 'TickDir', 'out');
ylabel(ax, 'Matched log_2 residual / media');
xlim(ax, [0.55, 5.45]);
end

function panelLabel(ax, label)
text(ax, -0.12, 1.08, label, 'Units', 'normalized', ...
    'FontName', 'Arial', 'FontSize', 15, 'FontWeight', 'bold', ...
    'VerticalAlignment', 'top');
end

function alignment = horizontalAlignment(value)
if value < 0; alignment = 'right'; else; alignment = 'left'; end
end
