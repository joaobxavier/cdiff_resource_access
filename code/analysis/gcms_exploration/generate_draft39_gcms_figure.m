%% Generate Draft 39 Figure 3 with paired PLS-DA panels
% Replaces the extracellular heat map in panel B with a descriptive PLS-DA
% biplot using the same five strains, three matched batches, strain colors,
% batch symbols, centroid markers, and descriptive ellipses as panel A.

clear;

scriptPath = mfilename('fullpath');
scriptFile = [scriptPath, '.m'];
localRoot = fileparts(fileparts(fileparts(scriptPath)));
repoRoot = fileparts(localRoot);
previewTableRoot = fullfile(repoRoot, 'results', 'tables', 'previews');
intracellularDir = fullfile(previewTableRoot, ...
    'gcms_intracellular_matched');
extracellularDir = fullfile(previewTableRoot, ...
    'gcms_biolog_concordance');
figureDir = fullfile(repoRoot, 'results', 'figures');
tableDir = fullfile(repoRoot, 'results', 'tables', 'main');
if ~isfolder(figureDir); mkdir(figureDir); end
if ~isfolder(tableDir); mkdir(tableDir); end

intraSource = package_input('intra.xlsx');
extraSource = package_input('secretome.xlsx');
intraWorkflow = fullfile(fileparts(scriptPath), ...
    'plot_intracellular_plsda_significant_background.m');
intraContrastWorkflow = fullfile(fileparts(scriptPath), ...
    'analyze_intracellular_matched_batches.m');
extraWorkflow = fullfile(fileparts(scriptPath), ...
    'analyze_extracellular_biolog_concordance.m');

scoreFile = fullfile(intracellularDir, ...
    'intracellular_descriptive_plsda_2d_scores.csv');
loadingFile = fullfile(intracellularDir, ...
    'intracellular_descriptive_plsda_2d_loadings.csv');
componentFile = fullfile(intracellularDir, ...
    'intracellular_descriptive_plsda_component_variance.csv');
screenFile = fullfile(intracellularDir, ...
    'intracellular_significantly_above_background_screen.csv');
intraFocusedFile = fullfile(intracellularDir, ...
    'st175_st168_matched_metabolite_effects.csv');
longFile = fullfile(extracellularDir, ...
    'extracellular_five_strain_long_form.csv');
globalFile = fullfile(extracellularDir, ...
    'extracellular_matched_global_strain_tests.csv');
focusedFile = fullfile(extracellularDir, ...
    'extracellular_st175_st168_matched_metabolite_tests.csv');
focusedPairFile = fullfile(extracellularDir, ...
    'extracellular_st175_st168_matched_pairs.csv');
requiredFiles = string({intraSource, extraSource, intraWorkflow, ...
    intraContrastWorkflow, extraWorkflow, scoreFile, loadingFile, ...
    componentFile, screenFile, intraFocusedFile, longFile, globalFile, ...
    focusedFile, focusedPairFile});
assert(all(isfile(requiredFiles)), ...
    'Run the matched-batch MATLAB workflows before composing Figure 3.');

scores = readtable(scoreFile, 'TextType', 'string');
loadings = readtable(loadingFile, 'TextType', 'string');
components = readtable(componentFile, 'TextType', 'string');
screen = readtable(screenFile, 'TextType', 'string');
intraFocused = readtable(intraFocusedFile, 'TextType', 'string');
long = readtable(longFile, 'TextType', 'string');
globalTests = readtable(globalFile, 'TextType', 'string');
focusedTests = readtable(focusedFile, 'TextType', 'string');
focusedPairs = readtable(focusedPairFile, 'TextType', 'string');

strainOrder = ["ST1-75", "ST1-68", "ST1-6", "VPI10463", "R20291"];
strainColors = [
    36, 104, 162;
    225, 97, 31;
    142, 90, 169;
    217, 71, 63;
    60, 157, 86] ./ 255;
batchMarkers = {'o', 's', '^'};

assert(height(scores) == 15 && numel(unique(scores.Strain)) == 5, ...
    'Expected 15 intracellular samples from five strains.');
assert(height(loadings) == 13 && sum(screen.IncludedInPlsDa) == 13, ...
    'Expected 13 intracellular features above matched background.');
assert(height(components) == 2, 'Expected two descriptive PLS components.');
assert(all(intraFocused.BenjaminiHochbergQ >= 0.05 | ...
    isnan(intraFocused.BenjaminiHochbergQ)), ...
    ['An intracellular ST1-75/ST1-68 metabolite now survives correction; ' ...
    'revisit the manuscript interpretation.']);
assert(sum(long.ContinuousFeature) == 15 * 13, ...
    'Expected 13 continuous extracellular features for 15 samples.');

continuousMetabolite = unique(long.Metabolite(logical(long.ContinuousFeature)), ...
    'stable');

%% Matched extracellular descriptive PLS-DA
% The input is the 13-metabolite matrix of batch-matched log2 residual signal
% relative to media. This mirrors the intracellular panel's standardization,
% five-column strain response, and two-component PLS regression.
sampleOrder = unique(long.Sample, 'stable');
nSample = numel(sampleOrder);
nMetabolite = numel(continuousMetabolite);
extraX = nan(nSample, nMetabolite);
extraStrain = strings(nSample, 1);
extraBatch = nan(nSample, 1);
for i = 1:nSample
    sampleRows = long.Sample == sampleOrder(i);
    extraStrain(i) = unique(long.Strain(sampleRows));
    extraBatch(i) = unique(long.Batch(sampleRows));
    for j = 1:nMetabolite
        valueRow = sampleRows & ...
            long.Metabolite == continuousMetabolite(j);
        assert(sum(valueRow) == 1, ...
            'Expected one value per extracellular sample and metabolite.');
        extraX(i, j) = long.MatchedLog2ResidualRatio(valueRow);
    end
end
assert(nSample == 15 && all(isfinite(extraX), 'all'), ...
    'Expected a complete 15-by-13 extracellular matrix.');

extraZ = (extraX - mean(extraX, 1)) ./ std(extraX, 0, 1);
extraResponse = zeros(nSample, numel(strainOrder));
for g = 1:numel(strainOrder)
    extraResponse(extraStrain == strainOrder(g), g) = 1;
end
[extraXLoading, ~, extraXScore, ~, ~, extraPercentVariance, ~, ...
    extraStats] = plsregress(extraZ, extraResponse, 2);
assert(size(extraXScore, 2) >= 2, ...
    'Two extracellular PLS components were not returned.');

extraScores = table(sampleOrder, extraStrain, extraBatch, ...
    extraXScore(:, 1), extraXScore(:, 2), 'VariableNames', ...
    {'Sample', 'Strain', 'Batch', 'PLS1Score', 'PLS2Score'});
extraLoadings = table(continuousMetabolite, extraXLoading(:, 1), ...
    extraXLoading(:, 2), extraStats.W(:, 1), extraStats.W(:, 2), ...
    'VariableNames', {'Metabolite', 'PLS1Loading', 'PLS2Loading', ...
    'PLS1Weight', 'PLS2Weight'});
extraComponents = table(["PLS1"; "PLS2"], ...
    extraPercentVariance(1, 1:2)', extraPercentVariance(2, 1:2)', ...
    'VariableNames', {'Component', 'XVarianceFraction', ...
    'YVarianceFraction'});
assert(all(round(100 .* extraComponents.XVarianceFraction, 2) == ...
    [39.88; 30.03]), ...
    'Extracellular PLS X-variance fractions changed unexpectedly.');

prolineGlobal = globalTests(globalTests.Metabolite == "Proline", :);
glutamateGlobal = globalTests(globalTests.Metabolite == "Glutamate", :);
prolineFocused = focusedTests(focusedTests.Metabolite == "Proline", :);
assert(height(prolineGlobal) == 1 && height(glutamateGlobal) == 1 && ...
    height(prolineFocused) == 1, 'Required GC-MS test rows are unavailable.');
assert(abs(prolineFocused.PairedTP - 0.00313) < 5e-5 && ...
    abs(prolineFocused.BenjaminiHochbergQAcrossNonconstantMetabolites - ...
    0.04698) < 5e-5, 'Focused proline result changed unexpectedly.');

% Copy the exact tables used by the figure into the versioned output folder.
writetable(scores, fullfile(tableDir, 'figure3_intracellular_plsda_scores.csv'));
writetable(loadings, fullfile(tableDir, ...
    'figure3_intracellular_plsda_loadings.csv'));
writetable(components, fullfile(tableDir, ...
    'figure3_intracellular_plsda_component_variance.csv'));
writetable(screen, fullfile(tableDir, ...
    'figure3_intracellular_background_screen.csv'));
writetable(intraFocused, fullfile(tableDir, ...
    'figure3_intracellular_st175_st168_matched_tests.csv'));
writetable(long, fullfile(tableDir, ...
    'figure3_extracellular_long_form.csv'));
writetable(globalTests, fullfile(tableDir, ...
    'figure3_extracellular_global_tests.csv'));
writetable(focusedTests, fullfile(tableDir, ...
    'figure3_st175_st168_matched_tests.csv'));
writetable(focusedPairs, fullfile(tableDir, ...
    'figure3_st175_st168_matched_pairs.csv'));
writetable(extraScores, fullfile(tableDir, ...
    'figure3_extracellular_plsda_scores.csv'));
writetable(extraLoadings, fullfile(tableDir, ...
    'figure3_extracellular_plsda_loadings.csv'));
writetable(extraComponents, fullfile(tableDir, ...
    'figure3_extracellular_plsda_component_variance.csv'));

%% Figure
fig = figure('Visible', 'off', 'Color', 'w', 'Units', 'inches', ...
    'Position', [0.2, 0.2, 13.5, 9.7]);
% Match Xavier's manual Illustrator presentation (2026-09-17).

axA = axes(fig, 'Position', [0.065, 0.56, 0.425, 0.40]);
plotPlsdaBiplot(axA, scores, loadings, components, strainOrder, ...
    strainColors, batchMarkers, {'Intracellular metabolite pools'}, true, 1);
panelLabel(axA, 'A');

axB = axes(fig, 'Position', [0.56, 0.56, 0.425, 0.40]);
plotPlsdaBiplot(axB, extraScores, extraLoadings, extraComponents, ...
    strainOrder, strainColors, batchMarkers, ...
    {'Extracellular metabolite remodeling'}, false, 2);
panelLabel(axB, 'B');

axC = axes(fig, 'Position', [0.065, 0.105, 0.425, 0.36]);
plotExtracellularMetabolite(axC, long, "Proline", strainOrder, ...
    strainColors, true);
title(axC, sprintf('Proline (strain effect q=%.3g)', ...
    prolineGlobal.BenjaminiHochbergQ), 'FontWeight', 'bold');
text(axC, 0.02, 0.72, sprintf(['ST1-75/ST1-68 residual ratio %.3f\n' ...
    'paired p=%.3g; q=%.3g'], ...
    prolineFocused.GeometricResidualSignalRatio_ST1_75_Over_ST1_68, ...
    prolineFocused.PairedTP, ...
    prolineFocused.BenjaminiHochbergQAcrossNonconstantMetabolites), ...
    'Units', 'normalized', 'FontName', 'Arial', 'FontSize', 8.5, ...
    'VerticalAlignment', 'bottom', 'BackgroundColor', 'w', ...
    'EdgeColor', [0.84, 0.84, 0.84], 'Margin', 3);
panelLabel(axC, 'C');

axD = axes(fig, 'Position', [0.57, 0.105, 0.415, 0.36]);
